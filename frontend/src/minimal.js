import * as THREE from 'three/webgpu';
const canvas = document.getElementById('c');
const renderer = new THREE.WebGPURenderer({ canvas, antialias: true });
await renderer.init();
renderer.setSize(640, 360);
renderer.toneMapping = THREE.ACESFilmicToneMapping;
const scene = new THREE.Scene();
scene.background = new THREE.Color(0x223344);
const camera = new THREE.PerspectiveCamera(50, 640/360, 0.1, 100);
camera.position.set(0,0,5);
const mesh = new THREE.Mesh(new THREE.BoxGeometry(1,1,1), new THREE.MeshBasicMaterial({color:0xff0000}));
scene.add(mesh);
scene.add(new THREE.HemisphereLight(0xffffff,0x444444,1));
renderer.debug.checkShaderErrors = true;
const dev = renderer.backend.device;
dev.addEventListener('uncapturederror', e=>console.error('uncaptured',e.error?.message||e.error));
dev.lost.then(i=>console.error('lost',i.message));
renderer.render(scene,camera);
await dev.queue.onSubmittedWorkDone();
window.__ready = true;
window.__data = canvas.toDataURL();
