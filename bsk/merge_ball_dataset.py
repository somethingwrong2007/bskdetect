"""把真实 Roboflow 球数据与 WebGPU 3D 合成球数据混合成 YOLO 单类数据集。

真实数据：data/external/ball_real_yolo（CC BY 4.0）
合成数据：data/ball_synth3d（pygfx/wgpu BSD-2-Clause 场景生成）
输出：data/ball_mix3d/{train,valid,test}/{images,labels} + data.yaml

图像优先硬链接，避免重复占盘；标签复制重命名。脚本不会覆盖非空输出目录。
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path

import numpy as np

SPLITS = ("train", "valid", "test")
DEFAULT_REAL = Path("data/external/ball_real_yolo")
DEFAULT_SYNTH = Path("data/ball_synth3d")
DEFAULT_OUT = Path("data/ball_mix3d")


def _link_or_copy(src: Path, dst: Path) -> str:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        raise FileExistsError(dst)
    try:
        os.link(src, dst)
        return "hardlink"
    except OSError:
        shutil.copy2(src, dst)
        return "copy"


def _copy_label(src: Path, dst: Path) -> int:
    """复制单类标签并把越界框裁回图像范围，返回保留框数。"""
    rows: list[str] = []
    for line in src.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) != 5 or int(float(parts[0])) != 0:
            continue
        cx, cy, bw, bh = (float(v) for v in parts[1:])
        x0, x1 = max(0.0, cx - bw / 2), min(1.0, cx + bw / 2)
        y0, y1 = max(0.0, cy - bh / 2), min(1.0, cy + bh / 2)
        if x1 - x0 < 1e-6 or y1 - y0 < 1e-6:
            continue
        rows.append(f"0 {(x0 + x1) / 2:.6f} {(y0 + y1) / 2:.6f} "
                    f"{x1 - x0:.6f} {y1 - y0:.6f}\n")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("".join(rows), encoding="utf-8")
    return len(rows)


def merge(real_root: Path = DEFAULT_REAL, synth_root: Path = DEFAULT_SYNTH,
          out_root: Path = DEFAULT_OUT, seed: int = 0,
          ratios: tuple[float, float, float] = (0.8, 0.1, 0.1)) -> dict:
    real_root, synth_root, out_root = Path(real_root), Path(synth_root), Path(out_root)
    if out_root.exists() and any(out_root.iterdir()):
        raise FileExistsError(f"输出目录非空，拒绝覆盖：{out_root}")
    if not (real_root / "train" / "images").exists():
        raise FileNotFoundError(f"真实数据集不存在：{real_root}")
    if not (synth_root / "images").exists() or not (synth_root / "labels").exists():
        raise FileNotFoundError(f"合成数据集不存在：{synth_root}")

    report = {"real": str(real_root.resolve()), "synth": str(synth_root.resolve()),
              "out": str(out_root.resolve()), "splits": {}}
    # 真实数据：保留原 split 和原始框
    for split in SPLITS:
        src_img = real_root / split / "images"
        src_lbl = real_root / split / "labels"
        if not src_img.exists():
            continue
        n_img = n_box = 0
        ways = {"hardlink": 0, "copy": 0}
        for img in sorted(src_img.iterdir()):
            if img.suffix.lower() not in (".jpg", ".jpeg", ".png"):
                continue
            lbl = src_lbl / f"{img.stem}.txt"
            if not lbl.exists():
                continue
            ways[_link_or_copy(img, out_root / split / "images" / f"real_{img.name}")] += 1
            n_box += _copy_label(lbl, out_root / split / "labels" / f"real_{img.stem}.txt")
            n_img += 1
        report["splits"][split] = {"real_images": n_img, "real_boxes": n_box,
                                    "real_methods": ways}

    # 合成数据：flat images/labels 确定性分层
    syn_imgs = sorted((synth_root / "images").glob("*.jpg"))
    syn_imgs += sorted((synth_root / "images").glob("*.png"))
    syn_imgs = [p for p in syn_imgs if (synth_root / "labels" / f"{p.stem}.txt").exists()]
    order = np.random.default_rng(seed).permutation(len(syn_imgs))
    syn_imgs = [syn_imgs[int(i)] for i in order]
    n = len(syn_imgs)
    n_train = int(round(n * ratios[0]))
    n_val = int(round(n * ratios[1]))
    parts = {"train": syn_imgs[:n_train],
             "valid": syn_imgs[n_train:n_train + n_val],
             "test": syn_imgs[n_train + n_val:]}
    for split in SPLITS:
        n_img = n_box = 0
        for img in parts[split]:
            lbl = synth_root / "labels" / f"{img.stem}.txt"
            _link_or_copy(img, out_root / split / "images" / f"synth_{img.name}")
            n_box += _copy_label(lbl, out_root / split / "labels" / f"synth_{img.stem}.txt")
            n_img += 1
        report["splits"].setdefault(split, {}).update({"synth_images": n_img, "synth_boxes": n_box})

    for split in SPLITS:
        r = report["splits"].setdefault(split, {})
        r["total_images"] = r.get("real_images", 0) + r.get("synth_images", 0)
        r["total_boxes"] = r.get("real_boxes", 0) + r.get("synth_boxes", 0)

    (out_root / "data.yaml").write_text(
        "# Generated by bsk.merge_ball_dataset\n"
        "# Real: Roboflow Basketball Detection v1 (CC BY 4.0)\n"
        "# Synthetic: bsk.synth3d / pygfx / wgpu (BSD-2-Clause)\n"
        f"path: {out_root.resolve().as_posix()}\n"
        "train: train/images\nval: valid/images\ntest: test/images\nnc: 1\nnames: ['ball']\n",
        encoding="utf-8",
    )
    (out_root / "merge_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="混合真实与 3D 合成球检测数据")
    ap.add_argument("--real", type=Path, default=DEFAULT_REAL)
    ap.add_argument("--synth", type=Path, default=DEFAULT_SYNTH)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    print(json.dumps(merge(args.real, args.synth, args.out, args.seed), indent=2))
